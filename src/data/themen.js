export const THEMEN_WORDS = CATEGORIES.flatMap((c) =>
  c.words.map(([de, en, article, ex_de, ex_en]) => ({
    n: ++n,
    de, en,
    article: article || null,
    ex_de, ex_en,
    cat: c.id,
    catName: c.de,
    full: article ? `${article} ${de}` : de,
  }))
);

export const wordsOf = (catId) => THEMEN_WORDS.filter((w) => w.cat === catId);
export const TOTAL = THEMEN_WORDS.length;

