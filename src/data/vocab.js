/* Dedupe on word+type so genuine homographs survive as separate cards
   (sein = "to be" / "his"; zu = "to" / "too") while accidental repeats
   of the same word in the same role collapse to one. */
const seen = new Set();
export const VOCAB = W.filter(([de, , , , type]) => {
  const k = `${de}|${type}`;
  if (seen.has(k)) return false;
  seen.add(k);
  return true;
}).map(([de, en, article, plural, type, ex_de, ex_en, ch, tags], i) => ({
  id: `w${i + 1}`,
  de, en, article: article || null, plural: plural || null,
  type, ex_de, ex_en, ch, tags: tags.split(" "),
  /* display form: nouns are always learned with their article */
  full: article ? `${article} ${de}` : de,
}));

export const NOUNS = VOCAB.filter((w) => w.article);
export const byChapter = (ch) => VOCAB.filter((w) => w.ch === ch);
export const byTag = (t) => VOCAB.filter((w) => w.tags.includes(t));
